def _model() -> LeagueModel:
    raw = json.loads((REPO_ROOT / "tests" / "fixtures" / "week02-nailbiter.json").read_text(encoding="utf-8"))
    base = build_league_model({k: raw[k] for k in ("league", "draft", "draft_picks", "rosters", "users")})
    fmt = LeagueFormat(
        team_count=3,
        roster_slots=["QB", "RB", "RB", "WR", "WR", "TE", "FLEX", "K", "DEF"],
        flex_eligibility={"FLEX": ["RB", "WR", "TE"]},
        scoring_label="PPR",
        is_superflex_or_2qb=False,
        te_premium=False,
    )
    return base.model_copy(update={"format": fmt, "season": 2026})


class Net:
    """A recording nflverse transport over the committed fixtures."""

    def __init__(self, *, status: int = 200, broken: str | None = None) -> None:
        self.urls: list[str] = []
        self.status = status
        self.broken = broken

    def __call__(self, request: httpx.Request) -> httpx.Response:
        self.urls.append(str(request.url))
        if self.status != 200:
            return httpx.Response(self.status)
        name = request.url.path.rsplit("/", 1)[1].removesuffix(".gz")
        if self.broken and name.startswith(self.broken):
            return httpx.Response(200, content=b"not a gzip file")
        return httpx.Response(200, content=gzip.compress((FX / name).read_bytes()))

    def client(self) -> httpx.Client:
        return httpx.Client(transport=httpx.MockTransport(self))


def _run(
    store: FileStore,
    *,
    net: Net | None = None,
    source: str = "nflverse",
    league: dict[str, Any] | None = None,
    model: LeagueModel | None = None,
    players: dict[str, Any] | None = None,
    league_id: str = LEAGUE_ID,
) -> dict[str, Any]:
    net = net or Net()
    snap = league_value_for_week(
        store,
        league_id,
        WEEK,
        model=model or _model(),
        league=league or BUNDLE["league"],
        matchups=BUNDLE["matchups"],
        players=players or BUNDLE["players"],
        standings_order=BUNDLE["standings_order"],
        source=source,
        client=net.client(),
    )
    assert snap is not None
    return snap


