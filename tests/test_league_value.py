def test_replacement_comes_from_a_greedy_fill_of_every_teams_lineup(snap: dict[str, Any]) -> None:
    """3 teams, 1 QB / 2 RB / 2 WR / 1 TE / 1 FLEX: 3 QB, 6 RB, 6 WR, 3 TE start, then 3 flex from what is left."""
    by_pos: dict[str, list[float]] = {}
    for info in snap["players"].values():
        if info["ppg"] is not None and info["pos"] in ("QB", "RB", "WR", "TE"):
            by_pos.setdefault(info["pos"], []).append(info["ppg"])
    for ppgs in by_pos.values():
        ppgs.sort(reverse=True)
    fixed = {"QB": by_pos["QB"][:3], "RB": by_pos["RB"][:6], "WR": by_pos["WR"][:6], "TE": by_pos["TE"][:3]}
    left = sorted((p for pos in ("RB", "WR", "TE") for p in by_pos[pos][len(fixed[pos]):]), reverse=True)
    flex = left[:3]
    for pos in ("RB", "WR", "TE"):
        starters = fixed[pos] + [p for p in flex if p in by_pos[pos][len(fixed[pos]):]]
        assert snap["replacement"][pos] == pytest.approx(min(starters), abs=1e-3), pos
    assert snap["replacement"]["QB"] == pytest.approx(min(fixed["QB"]), abs=1e-3)


